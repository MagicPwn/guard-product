export function translateDynamic(text: string): string {
  for (const entry of DYNAMIC_TRANSLATIONS) {
    const match = entry.pattern.exec(text);
    if (match) return entry.replace(match);
  }
  return text;
}

interface I18nValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (english: string, values?: Record<string, string | number>) => string;
  formatDate: (value: string | number | Date) => string;
  formatTime: (value: string | number | Date) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

function initialLanguage(): Language {
  const saved = localStorage.getItem(STORAGE_KEY);
  return saved === "en" ? "en" : DEFAULT_LANGUAGE;
}

function interpolate(text: string, values?: Record<string, string | number>): string {
  if (!values) return text;
  return Object.entries(values).reduce(
    (result, [key, value]) => result.split(`{${key}}`).join(String(value)),
    text
  );
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(initialLanguage);

  function setLanguage(next: Language) {
    localStorage.setItem(STORAGE_KEY, next);
    setLanguageState(next);
  }

  useEffect(() => {
    document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  }, [language]);

  const value = useMemo<I18nValue>(() => {
    const locale = language === "zh" ? "zh-CN" : "en-US";
    return {
      language,
      setLanguage,
      t: (english, values) => {
        const translated = language === "zh" ? translateEnglishToChinese(english) : english;
        return interpolate(translated, values);
      },
      formatDate: (input) => new Date(input).toLocaleString(locale),
      formatTime: (input) => new Date(input).toLocaleTimeString(locale)
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

export function translateEnglishToChinese(english: string): string {
  return ZH[english] ?? translateDynamic(english);
}

export function errorText(problem: unknown, fallback: string, t: I18nValue["t"]): string {
  return t(problem instanceof Error ? problem.message : fallback);
}

export function LanguageSwitcher() {
  const { language, setLanguage, t } = useI18n();
  return (
    <select className="language-select" aria-label={t("Language")} value={language}
      onChange={(event) => setLanguage(event.target.value === "en" ? "en" : "zh")}>
      <option value="zh">中文</option>
      <option value="en">English</option>
    </select>
  );
}
