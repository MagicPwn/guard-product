type DynamicTranslation = {
  pattern: RegExp;
  replace: (match: RegExpMatchArray) => string;
};

const POLICY_LABELS: Record<string, string> = {
  subject: "科目",
  grade: "年级",
  difficulty: "难度",
  language: "语言",
  tag: "标签"
};

function policyLabel(label: string): string {
  const trigger = /^trigger (\d+)$/.exec(label);
  if (trigger) return `触发规则 ${trigger[1]}`;
  return POLICY_LABELS[label] ?? label;
}

function questionField(field: string): string {
  return ({ id: "ID", prompt: "题目", subject: "科目", option: "选项", "accepted answer": "可接受答案" } as Record<string, string>)[field] ?? field;
}

